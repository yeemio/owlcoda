type Vars = Record<string, string | number | undefined>

interface I18nContextValue {
  lang: AdminLanguage
  setLang: (lang: AdminLanguage) => void
  t: (key: TranslationKey, vars?: Vars) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function readInitialLang(): AdminLanguage {
  if (typeof window === 'undefined') return 'en'
  const stored = window.localStorage.getItem(STORAGE_KEY)
  return stored === 'zh' ? 'zh' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AdminLanguage>(readInitialLang)
  const messages = lang === 'zh' ? zh : en
  const value = useMemo<I18nContextValue>(() => ({
    lang,
    setLang: next => {
      setLangState(next)
      if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, next)
    },
    t: (key, vars) => {
      const template = messages[key] ?? en[key] ?? key
      if (!vars) return template
      return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
    },
  }), [lang, messages])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  return context ?? {
    lang: 'en',
    setLang: () => {},
    t: (key, vars) => fallbackTranslate(key, vars),
  }
}

function fallbackTranslate(key: TranslationKey, vars?: Vars): string {
  const template = en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

export function LanguageToggle() {
  const { lang, setLang, t } = useI18n()
  return (
    <div className="language-toggle" aria-label={t('language')} data-testid="language-toggle">
      <button
        type="button"
        className={lang === 'en' ? 'active' : ''}
        onClick={() => setLang('en')}
        aria-pressed={lang === 'en'}
      >
        EN
      </button>
      <button
        type="button"
        className={lang === 'zh' ? 'active' : ''}
        onClick={() => setLang('zh')}
        aria-pressed={lang === 'zh'}
      >
        中文
      </button>
    </div>
  )
}
